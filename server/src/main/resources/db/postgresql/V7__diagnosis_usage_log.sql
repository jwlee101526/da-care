-- AI 상담 한 건의 모델 사용량. 실패·시간 초과·취소로 끝난 상담도 그때까지 쓴 토큰을 남긴다.
-- 사용자를 식별하는 값(이메일, IP)은 저장하지 않고 요청자 구분만 둔다.
CREATE TABLE diagnosis_usage_log (
    id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    subject_type VARCHAR(10) NOT NULL,
    outcome VARCHAR(10) NOT NULL,
    model VARCHAR(100),
    model_calls INTEGER NOT NULL,
    tool_calls INTEGER NOT NULL,
    duration_ms BIGINT NOT NULL,
    input_tokens BIGINT NOT NULL,
    cached_input_tokens BIGINT NOT NULL,
    output_tokens BIGINT NOT NULL,
    reasoning_tokens BIGINT NOT NULL,
    -- 집계 주의 시작일(월요일, 한국 시간). api_usage.period_start와 같은 기준이다.
    period_start DATE NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_diagnosis_usage_log_outcome
        CHECK (outcome IN ('COMPLETED', 'FAILED', 'TIMEOUT', 'CANCELLED'))
);

CREATE INDEX idx_diagnosis_usage_log_period ON diagnosis_usage_log (period_start);
